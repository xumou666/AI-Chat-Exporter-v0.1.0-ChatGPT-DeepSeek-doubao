/*
 * Renders the test fixtures through the real exporter and writes the results
 * into examples/ — used as living documentation and as a smoke check.
 *
 *   node tools/write-examples.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createEnv, mockFetch, fakePng } from '../tests/helpers/env.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'examples');
mkdirSync(OUT, { recursive: true });

const CASES = [
  { fixture: 'chatgpt.html', id: 'chatgpt' },
  { fixture: 'deepseek.html', id: 'deepseek' },
  { fixture: 'doubao.html', id: 'doubao' },
  { fixture: 'generic-random.html', id: 'generic' }
];

const written = [];

function save(name, data) {
  const target = path.join(OUT, name);
  writeFileSync(target, data);
  written.push({ name, bytes: Buffer.byteLength(data) });
}

for (const testCase of CASES) {
  const { NS, document } = createEnv(testCase.fixture);
  const extraction = NS.core.app.extract(document, { reasoning: true, toolCalls: true, citations: true });
  const conversation = extraction.conversation;
  const settings = { locale: 'zh-CN', toc: true, reasoning: true, citations: true, frontMatter: true };

  const markdown = NS.core.serialize.toMarkdown(conversation, settings);
  save(`${testCase.id}-sample.md`, markdown);
  save(`${testCase.id}-sample.json`, NS.core.serialize.toJSON(conversation, {}));
  save(`${testCase.id}-sample.html`, NS.core.html.buildHtmlDocument(conversation, { ...settings, includeReasoning: true }));
  save(`${testCase.id}-print.html`, NS.core.pdf.buildPrintDocument(conversation, { ...settings, includeReasoning: true, autoPrint: false }));
  console.log(`${testCase.id}: ${conversation.messageCount} messages, strategy=${extraction.strategy}`);

  if (testCase.id === 'chatgpt') {
    const packaged = await NS.core.app.exportPackage(conversation, {
      ...settings,
      format: 'md',
      fetchImpl: mockFetch({ 'https://cdn.example.com/chart.png': fakePng(96) })
    });
    save('chatgpt-with-images.zip', Buffer.from(packaged.bytes));
    console.log(`bundle: ${packaged.entries.map((entry) => entry.name).join(', ')}`);

    // Partial export demo: only messages #3 and #4 (1-based, inclusive).
    const partial = NS.core.app.extract(document, {
      reasoning: true,
      scope: { mode: 'range', from: 3, to: 4 }
    }).conversation;
    save('chatgpt-partial-messages-3-4.md', NS.core.serialize.toMarkdown(partial, settings));
    save('chatgpt-partial-messages-3-4.json', NS.core.serialize.toJSON(partial, {}));
    console.log(`partial export: ${partial.messageCount} messages, scope=${JSON.stringify(partial.meta.scope)}`);
  }
}

const listing = [
  '# Export samples',
  '',
  'Generated by `node tools/write-examples.mjs` from the HTML fixtures in `tests/fixtures/`.',
  'They show exactly what the extension writes for each supported site.',
  '',
  '| file | bytes |',
  '| --- | --- |',
  ...written.map((entry) => `| \`${entry.name}\` | ${entry.bytes} |`),
  '',
  '`*-print.html` is the document the PDF export opens; use the browser print',
  'dialog (Ctrl/Cmd + P) and pick "Save as PDF".',
  ''
].join('\n');
save('README.md', listing);
console.log(`\nwrote ${written.length} files to ${path.relative(ROOT, OUT)}/`);
